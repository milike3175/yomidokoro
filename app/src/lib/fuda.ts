// 揺れの印（ケンの判定）の札。県ページと府県くらべで、言葉と並べ方をそろえるために一か所に置く。
// 印を出すのは「揺れあり、要確認」「電話で補足」「手引きと一致」の三つ。「判定不能」は小さく灰色で。
// 「対象が違う」は data.ts の時点で外してある。解消（行政書士が確かめた）は消さずに弱める
import type { 判定の印, 判定の種類 } from "./data";
import { 品目で見る, 手続きが合う, type 手続き } from "./hantei";

export const 判定の順: 判定の種類[] = ["食い違い", "補足", "一致", "判定不能"];

/** 手引きのカードの側では、一致の相手は電話なので「電話と一致」と言う */
export function 判定の文(判定: 判定の種類, 種類: 判定の印["種類"], 手引きの側 = false) {
  if (判定 === "食い違い") return "揺れあり、要確認";
  if (判定 === "補足") return "電話で補足";
  if (判定 === "一致") return 種類 === "電話どうし" ? "前の電話と一致" : 手引きの側 ? "電話と一致" : "手引きと一致";
  return "判定不能";
}

export type 札 = { 判定: 判定の種類; 文: string; 解消: boolean; 理由たち: string[] };

/** カードに付ける札。同じ答えの組はまとめ、全部が確かめ済みのときだけ弱める */
export function 判定の札(js: 判定の印[], 手引きの側: boolean): 札[] {
  const 札たち: 札[] = [];
  for (const 判定 of 判定の順) {
    for (const 種類 of ["手引きと電話", "電話どうし"] as const) {
      const 組 = js.filter((j) => j.判定 === 判定 && j.種類 === 種類);
      if (組.length === 0) continue;
      const 文 = 判定の文(判定, 種類, 手引きの側);
      const 前 = 札たち.find((x) => x.文 === 文);
      const 理由たち = 組.map((j) => `Claude の理由：${j.理由}`);
      if (前) {
        前.解消 = 前.解消 && 組.every((j) => j.解消);
        前.理由たち.push(...理由たち);
      } else 札たち.push({ 判定, 文, 解消: 組.every((j) => j.解消), 理由たち });
    }
  }
  return 札たち;
}

// ---- どの組の札を出すか（県ページと府県くらべで同じ決まり） ----

/** 画面で選んでいる手続き・品目 */
export type 選び = { 手続き: 手続き; 品目: string; 品目一覧: { id: string; 建設系: boolean }[] };
type 観点の印 = { 品目で変わる: boolean } | undefined;

/** 記録が、選んだ手続き・品目に当てはまらない（薄くする）か */
export function 記録が薄い(c: { 対象: string[]; 品目?: string[] }, k: 観点の印, s: 選び): boolean {
  return !手続きが合う(c, s.手続き) || 品目で見る(c, k, s.品目, s.品目一覧) === "合わない";
}

/** 組の相手が、選んだ手続き・品目に当てはまるか */
export function 相手が合う(j: 判定の印, k: 観点の印, s: 選び): boolean {
  return !記録が薄い(j.相手, k, s);
}

/**
 * カードに札を出す組。記録が当てはまるときは、相手も当てはまる組だけ
 * （例：建設系以外の電話の「補足」を、がれき類を選んだときの手引きに付けない）。
 * 薄くした記録は札もいっしょに薄くなるので、組を絞らずにそのまま出す
 */
export function 札に出す判定(js: 判定の印[], 記録が薄く: boolean, k: 観点の印, s: 選び): 判定の印[] {
  return 記録が薄く ? js : js.filter((j) => 相手が合う(j, k, s));
}

/** 理由の一行（見比べ・見立て）を出す組：電話の側（主）の揺れと補足で、両方の記録が当てはまるものだけ */
export function 見立てに出す判定(js: 判定の印[], 記録が薄く: boolean, k: 観点の印, s: 選び): 判定の印[] {
  if (記録が薄く) return [];
  return js.filter((j) => j.主 && (j.判定 === "食い違い" || j.判定 === "補足") && 相手が合う(j, k, s));
}

/** 揺れを先に、確かめ済みは後ろに */
export const 見立ての順 = (a: 判定の印, b: 判定の印) =>
  Number(a.解消) - Number(b.解消) || 判定の順.indexOf(a.判定) - 判定の順.indexOf(b.判定);
