const 丸数字 = "①②③④⑤⑥⑦⑧⑨⑩⑪⑫⑬⑭⑮⑯⑰⑱⑲⑳";

/** くり返しで入っている組の番号（1 から。途中が空でも詰めない） */
export function 入っている組(型: 書き方の型, id: string, 値たち: 値): number[] {
  const 口 = 型.差し込み口.find((x) => x.id === id);
  if (!口 || 口.種類 !== "くり返し") return [];
  const r: number[] = [];
  for (let n = 1; n <= (口.最大 ?? 10); n++) {
    if ((口.項目 ?? []).some((k) => (値たち[くり返しの鍵(id, n, k.id)] ?? "").trim())) r.push(n);
  }
  return r;
}

const 行頭に来ない = /^[、。，．）」』】・：]/;
const 行末に来ない = /[（「『【]$/;

/** 一行の字数で切る。続きの行の頭に全角空白を置く。句読点・閉じ括弧は行頭に置かず、前の行に1字だけはみ出させる */
export function 折る(文: string, 幅: number, 続きの頭 = 0): string[] {
  const cs = Array.from(文);
  if (cs.length <= 幅) return [文];
  const 行: string[] = [];
  let 頭 = "";
  let i = 0;
  while (i < cs.length) {
    const w = 幅 - 字数(頭);
    let k = Math.min(cs.length, i + w);
    if (k < cs.length) {
      if (行頭に来ない.test(cs[k])) k += 1;
      else if (行末に来ない.test(cs[k - 1]) && k - 1 > i) k -= 1;
    }
    行.push(頭 + cs.slice(i, k).join(""));
    i = k;
    頭 = SP.repeat(続きの頭);
  }
  return 行;
}

/** 選んでいる形の行で使う差し込み口の id（画面で、使わない聞き取りの欄を出さないため） */
export function 使う口(型: 書き方の型, 値たち: 値, 印?: Record<string, boolean>): Set<string> {
  const r = new Set<string>();
  const 口 = new Map(型.差し込み口.map((x) => [x.id, x]));
  // くり返しの中の {項目} は、そのくり返しの口の項目なので数えない
  const 見る = (x: 型の行, 子たち: Set<string>) => {
    if (印 && x.条件 && !印[x.条件]) return;
    if (x.くり返し) r.add(x.くり返し);
    for (const t of [x.字, x.空なら ?? ""]) for (const m of t.matchAll(/\{([^{}]+)\}/g)) {
      if (子たち.has(m[1])) continue;
      r.add(m[1]);
      const d = 口.get(m[1]);
      if (d?.空なら) r.add(d.空なら);
    }
    const 次 = x.くり返し ? new Set([...子たち, ...(口.get(x.くり返し)?.項目 ?? []).map((k) => k.id)]) : 子たち;
    (x.行 ?? []).forEach((c) => 見る(c, 次));
  };
  for (const k of 型.欄) 欄の行(k, 値たち).forEach((x) => 見る(x, new Set()));
  return r;
}

/** 型に控えと聞き取りを差し込み、様式に書く行を作る（記入と画面の見込みの両方で使う） */
export function 型を組む(型: 書き方の型, 様: 様式, 値たち: 値, 中身0: 申請の中身 | undefined): 型の結果[] {
  const 印 = 中身の印(様, 中身0);
  const 口 = new Map(型.差し込み口.map((x) => [x.id, x]));
  const 自動: Record<string, string> = { 品目の並び: 品目を文に(様, 中身0) };

  const 結果: 型の結果[] = [];
  for (const 欄 of 型.欄) {
    const 場所 = 様.文の欄?.find((x) => x.id === 欄.id);
    if (!場所) continue;
    const 要確認: string[] = [];
    const 空き口 = new Set<string>();

    type 組 = { id: string; n: number | string; 番: number; 品目?: string };
    const 差す = (字: string, 組?: 組): string =>
      字.replace(/\{([^{}]+)\}/g, (_, 名: string) => {
        if (組 && 名 === "番号") return 丸数字[組.番 - 1] ?? `（${組.番}）`;
        if (組 && 名 === "品目" && 組.品目 !== undefined) return 組.品目;
        const 子 = 組 ? 口.get(組.id)?.項目?.find((k) => k.id === 名) : undefined;
        if (組 && 子) {
          const v = 全角に((値たち[くり返しの鍵(組.id, 組.n, 名)] ?? "").trim());
          if (v) return v;
          空き口.add(組.品目 !== undefined ? `${組.品目}の「${子.見出し}」` : `${口.get(組.id)!.見出し}の${組.番}組目の「${子.見出し}」`);
          return `【要確認：${子.見出し}】`;
        }
        const d = 口.get(名);
        if (!d) return `【要確認：${名}】`;
        if (d.種類 === "自動") {
          const v = 自動[名] ?? "";
          if (v) return v;
          空き口.add(d.見出し);
          return `【要確認：${d.見出し}】`;
        }
        const v = 全角に((値たち[型の鍵(名)] ?? "").trim());
        if (v) return v;
        if (d.空なら && 自動[d.空なら]) return 自動[d.空なら];
        空き口.add(d.見出し);
        return `【要確認：${d.見出し}】`;
      });

    // 行を出す（落とせる行に印を付けておく）
    // 守る：欄に収まらなくても必ず書く行。品目番：品目ごとのくり返しの何番目の品目の行か
    const 出し: { 字: string[]; 落とせる: boolean; 守る?: boolean; 品目番?: number }[] = [];
    const 出す = (r: 型の行, 組?: 組) => {
      if (r.条件 && !印[r.条件]) return;
      if (r.くり返し && 口.get(r.くり返し)?.種類 === "品目ごと") {
        // 控えの品目ごとに行を出す（品目の名前は 品目の並べ方.文 の形）
        品目の名たち(様, 中身0).forEach((h, j) => (r.行 ?? []).forEach((c) => 出す(c, { id: r.くり返し!, n: h.鍵, 番: j + 1, 品目: h.名 })));
        return;
      }
      if (r.くり返し) {
        const 組たち = 入っている組(型, r.くり返し, 値たち);
        if (組たち.length === 0) {
          if (r.空なら) {
            空き口.add(口.get(r.くり返し)?.見出し ?? r.くり返し);
            出し.push({ 字: 折る(差す(r.空なら), 場所.一行の字数, r.続きの頭 ?? 0), 落とせる: false });
          }
          return;
        }
        組たち.forEach((n, j) => (r.行 ?? []).forEach((c) => 出す(c, { id: r.くり返し!, n, 番: j + 1 })));
        return;
      }
      if (r.字 === "") {
        出し.push({ 字: [""], 落とせる: !!r.落とせる });
        return;
      }
      出し.push({
        字: 折る(差す(r.字, 組), 場所.一行の字数, r.続きの頭 ?? 0),
        落とせる: !!r.落とせる,
        守る: !!r.守る,
        品目番: 組?.品目 !== undefined ? 組.番 : undefined,
      });
    };
    for (const r of 欄の行(欄, 値たち)) 出す(r);

    // 行が足りなければ、落とせる行を下から落とす
    const 数 = () => 出し.reduce((a, b) => a + b.字.length, 0);
    for (let j = 出し.length - 1; j >= 0 && 数() > 場所.書く行; j--) if (出し[j].落とせる) 出し.splice(j, 1);
    // まだ足りなければ、品目ごとの行を下の品目から削り、削った品目の数を1行の【要確認】にまとめて残す（2026-11-04 夜 ジョブズの判断）
    let 削った = 0;
    while (数() > 場所.書く行) {
      const 番たち = 出し.map((x) => x.品目番).filter((n): n is number => n !== undefined);
      if (番たち.length === 0) break;
      const 最後 = Math.max(...番たち);
      const 位置 = 出し.findIndex((x) => x.品目番 === 最後);
      for (let j = 出し.length - 1; j >= 0; j--) if (出し[j].品目番 === 最後) 出し.splice(j, 1);
      const 前のまとめ = 出し.findIndex((x) => x.品目番 === -1);
      if (前のまとめ >= 0) 出し.splice(前のまとめ, 1);
      削った += 1;
      const 頭 = SP.repeat(2);
      出し.splice(前のまとめ >= 0 ? Math.min(位置, 前のまとめ) : 位置, 0, {
        字: 折る(`${頭}【要確認：ほかに${全角に(String(削った))}品目（欄に収まりません。別紙など）】`, 場所.一行の字数, 2),
        落とせる: false,
        守る: true,
        品目番: -1,
      });
    }
    if (削った) 要確認.push(`品目の行が欄（${場所.書く行}行）に収まらないので、下の ${削った}品目を「【要確認：ほかに…品目】」の1行にまとめました。別紙にするかなどを確かめてください`);
    // 守る行（営業範囲など）は必ず書き、残りの行数にほかの行を上から入れる
    while (出し.length && 出し[出し.length - 1].字.every((t) => t === "") && !出し[出し.length - 1].守る) 出し.pop();
    let 残り = 場所.書く行 - 出し.filter((x) => x.守る).reduce((a, b) => a + b.字.length, 0);
    const 行たち: string[] = [];
    const あふれ: string[] = [];
    for (const x of 出し) {
      for (const t of x.字) {
        if (x.守る) 行たち.push(t);
        else if (残り > 0) {
          行たち.push(t);
          残り -= 1;
        } else あふれ.push(t);
      }
    }
    // 末尾の空けた行は書かない
    while (行たち.length && 行たち[行たち.length - 1] === "") 行たち.pop();
    if (行たち.length > 場所.書く行) あふれ.push(...行たち.splice(場所.書く行));
    if (あふれ.length) 要確認.push(`欄（${場所.書く行}行）に収まりません。収まらない ${あふれ.length}行（${あふれ.join("／")}）は書いていません。文を短くするか、別紙にするかを確かめてください`);
    if (空き口.size) 要確認.push(`聞き取りが空の所に「【要確認：…】」を残しました：${[...空き口].join("、")}`);
    if (欄.注) 要確認.push(欄.注);
    const 形 = 選んだ形(欄, 値たち);
    結果.push({ id: 欄.id, 見出し: 場所.見出し, 行たち, あふれ, 要確認, 形: 形?.id });
  }
  return 結果;
}

