const 含むか = (v: 含み | undefined) => v === "両方" || v === "だけ";

/** この様式で、この品目に、この区分を選べるか（様式の対応表の 区分の品目） */
export function 区分がある(様: 様式 | null | undefined, id: string, k: 区分): boolean {
  return !!様?.区分の品目?.[k]?.includes(id);
}

/** 古い控えの true/false も読む。true は「両方」（前の形は「除く」と「含む」の2行を書いていたため）、それ以外は「含まない」 */
function 含みに(v: unknown): 含み | undefined {
  if (v === "両方" || v === "だけ") return v;
  if (v === true) return "両方";
  return undefined;
}

/**
 * 選んだ品目を施行令の順に並べ、知らない品目と形の違う値を落とす。
 * 様式を渡すと、その様式で選べない区分も落とす（「含まない」は書かない＝無いのと同じ）
 */
export function 中身を整える(中身: 申請の中身 | undefined, 様?: 様式 | null): 申請の中身 {
  if (!中身) return { ...空の中身, 品目: [] };
  const 選 = new Map(中身.品目.map((x) => [x.id, x]));
  const 品目: 品目の選び[] = [];
  const 選べる = (id: string, k: 区分) => (様 ? 区分がある(様, id, k) : true);
  for (const h of 品目たち) {
    const x = 選.get(h.id) as (品目の選び & Record<string, unknown>) | undefined;
    if (!x) continue;
    const y: 品目の選び = { id: h.id };
    const a = 含みに(x.石綿);
    if (a && 選べる(h.id, "石綿")) y.石綿 = a;
    if (x.水銀使用製品 === true && 選べる(h.id, "水銀使用製品")) y.水銀使用製品 = true;
    const m = 含みに(x.水銀含有ばいじん等);
    if (m && 選べる(h.id, "水銀含有ばいじん等")) y.水銀含有ばいじん等 = m;
    品目.push(y);
  }
  const 積替保管 = 中身.積替保管 === "有" || 中身.積替保管 === "無" ? 中身.積替保管 : "";
  return { 品目, 積替保管 };
}

