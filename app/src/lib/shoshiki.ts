    const err = 元と同じか一字(g.箱, g.字, `${g.面}の前`);
    if (err) return { ok: false, 理由: err };
    const 段 = 箱の段落(g.箱);
    if (!段) return { ok: false, 理由: `${g.面}の前：段落が見つかりません。書きません` };
