  // ---- 様式の面の変わり目で改ページ（2026-11-04 夜 みゆき「次の様式に変わるところできちんとページを変えてほしい」） ----
  // 前の面の最後の段落の末尾に、改ページだけの run を足す（みゆきが Word で案B8 を見て決めた形）。
  // 面の頭の段落に w:pageBreakBefore を付けるやり方は、浮いた表とつながる段落で Word が崩れたのでやめた。
