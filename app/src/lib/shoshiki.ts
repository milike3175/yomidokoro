/**
 * pos（w:t の位置）を含む run を、「前の字」「EQ フィールドの囲い文字」「後ろの字」の run に差し替える形を作る。
 * 形は _申請/試し/道具 の丸の試し（2026-11-04 夜 みゆきが Word で「丸も付けられている」）と同じ：
 *   <w:r>rPr<w:t>前</w:t></w:r> <w:r>rPr<w:fldChar begin/></w:r> <w:r>rPr<w:instrText xml:space="preserve"> eq \o\ac(</w:instrText></w:r>
 *   <w:r>rPr＋position・sz<w:instrText>○</w:instrText></w:r> <w:r>rPr<w:instrText>,有)</w:instrText></w:r> <w:r>rPr<w:fldChar end/></w:r> <w:r>rPr<w:t>後ろ</w:t></w:r>
 * 書式は元の run の rPr を写す。run の中に w:t が一つだけのときだけ作る
 */
function 丸のrun(
  本文: string,
  pos: number,
  字: string,
  囲む: "有" | "無",
  書式: { position: number; sz: number },
): { 始め: number; 終わり: number; 字: string } | null {
  const a = 本文.lastIndexOf("<w:r>", pos);
  const b = 本文.lastIndexOf("<w:r ", pos);
  const 始め = Math.max(a, b);
  if (始め < 0) return null;
  const 閉じ = 本文.indexOf("</w:r>", pos);
  if (閉じ < 0) return null;
  const run = 本文.slice(始め, 閉じ + 6);
  const m = /^<w:r(?: [^>]*)?>(<w:rPr>(?:(?!<\/w:rPr>)[\s\S])*<\/w:rPr>)?<w:t(?: [^>]*)?>[^<]*<\/w:t><\/w:r>$/.exec(run);
  if (!m) return null;
  const rPr = m[1] ?? "";
  const k0 = 字.indexOf("【有・無】");
  if (k0 < 0) return null;
  const k = k0 + 1 + (囲む === "有" ? 0 : 2);
  const 前 = 字.slice(0, k);
  const 後ろ = 字.slice(k + 1);
  const 足し = `<w:position w:val="${書式.position}"/><w:sz w:val="${書式.sz}"/>`;
  const 大 = rPr ? rPr.replace(/<w:position [^>]*\/>|<w:sz [^>]*\/>/g, "").replace("</w:rPr>", 足し + "</w:rPr>") : `<w:rPr>${足し}</w:rPr>`;
  const R = (中: string, p = rPr) => `<w:r>${p}${中}</w:r>`;
  const xml =
    R(`<w:t>${esc(前)}</w:t>`) +
    R(`<w:fldChar w:fldCharType="begin"/>`) +
    R(`<w:instrText xml:space="preserve"> eq \\o\\ac(</w:instrText>`) +
    R(`<w:instrText>○</w:instrText>`, 大) +
    R(`<w:instrText>,${囲む})</w:instrText>`) +
    R(`<w:fldChar w:fldCharType="end"/>`) +
    R(`<w:t>${esc(後ろ)}</w:t>`);
  return { 始め, 終わり: 閉じ + 6, 字: xml };
}

/** pos（w:t の位置）を含む run を、同じ書式で行たちを改行（w:br）でつないだ run に置き換える形。run の中に w:t が一つだけのときだけ作る */
function 改行のrun(本文: string, pos: number, 行たち: string[]): { 始め: number; 終わり: number; 字: string } | null {
  const 始め = Math.max(本文.lastIndexOf("<w:r>", pos), 本文.lastIndexOf("<w:r ", pos));
  if (始め < 0) return null;
  const 閉じ = 本文.indexOf("</w:r>", pos);
  if (閉じ < 0) return null;
  const run = 本文.slice(始め, 閉じ + 6);
  const m = /^(<w:r(?: [^>]*)?>)(<w:rPr>(?:(?!<\/w:rPr>)[\s\S])*<\/w:rPr>)?<w:t(?: [^>]*)?>[^<]*<\/w:t><\/w:r>$/.exec(run);
  if (!m) return null;
  const 中 = 行たち.map((t) => `<w:t xml:space="preserve">${esc(t)}</w:t>`).join("<w:br/>");
  return { 始め, 終わり: 閉じ + 6, 字: `${m[1]}${m[2] ?? ""}${中}</w:r>` };
}

// ---------------- 段落 ----------------

type 段落 = {
  始め: number;
  /** 閉じタグ（</w:p>）の始まり。run を足す位置 */
  閉じ: number;
  終わり: number;
  /** run も文字も無い段落 */
  空: boolean;
};

const 段落の印 = /<w:p(?=[\s>/])[^>]*?(\/?)>|<\/w:p>/g;

/** 本文の w:p を、始まりの順に数える（入れ子の段落も1つと数える）。組み立てが崩れていれば null */
function 段落を数える(本文: string): 段落[] | null {
  const 並び: 段落[] = [];
  const 積み: { k: number; 中の始め: number }[] = [];
  for (const m of 本文.matchAll(段落の印)) {
    if (m[0] === "</w:p>") {
      const t = 積み.pop();
      if (!t) return null;
      const 中 = 本文.slice(t.中の始め, m.index!);
      並び[t.k] = { ...並び[t.k], 閉じ: m.index!, 終わり: m.index! + 6, 空: !/<w:r[\s>]/.test(中) && !/<w:t[\s>]/.test(中) };
    } else if (m[1] === "/") {
      並び.push({ 始め: m.index!, 閉じ: -1, 終わり: m.index! + m[0].length, 空: false });
    } else {
      並び.push({ 始め: m.index!, 閉じ: -1, 終わり: -1, 空: false });
      積み.push({ k: 並び.length - 1, 中の始め: m.index! + m[0].length });
    }
  }
  if (積み.length) return null;
  return 並び;
}

/** pos を含む、いちばん内側の段落 */
function 段落の中(並び: 段落[], pos: number): 段落 | null {
  let r: 段落 | null = null;
  for (const p of 並び) if (p.始め <= pos && pos < p.終わり) r = p;
  return r;
}

/** pos（w:t の位置）を含む run の w:rPr。書式が無ければ ""、run が見つからなければ null */
function runの書式(本文: string, pos: number): string | null {
  const a = 本文.lastIndexOf("<w:r>", pos);
  const b = 本文.lastIndexOf("<w:r ", pos);
  const 始め = Math.max(a, b);
  if (始め < 0) return null;
  const 間 = 本文.slice(始め, pos);
  if (/<\/w:r>/.test(間)) return null;
  const m = /^<w:r(?: [^>]*)?>(<w:rPr>[\s\S]*?<\/w:rPr>)?/.exec(間);
  if (!m) return null;
  return m[1] ?? "";
}

